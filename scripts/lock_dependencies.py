"""Refresh exact dependency locks from the tested environment and PyPI hashes.
Run manually with the tested backend interpreter; review version/rights changes.
"""
from importlib.metadata import distribution
from pathlib import Path
import json,urllib.request
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
ROOT=Path(__file__).resolve().parents[1]
PROD=['fastapi','uvicorn','requests','numpy','rasterio','pyproj','reportlab','Pillow']
DEV=PROD+['pytest','pypdf','httpx','python-dotenv']
def closure(roots):
    found={};pending=list(roots)
    while pending:
        name=canonicalize_name(pending.pop())
        if name in found:continue
        dist=distribution(name);found[name]=dist
        for raw in dist.requires or []:
            req=Requirement(raw)
            if req.marker is None or req.marker.evaluate({'extra':''}):pending.append(req.name)
    return found
cache={}
for filename,roots in [('requirements.lock',PROD),('requirements-dev.lock',DEV)]:
    packages=closure(roots);lines=['# Exact tested dependency closure. Generated by scripts/lock_dependencies.py.','# Install with --require-hashes --only-binary=:all:. Python 3.11.']
    for name,dist in sorted(packages.items()):
        key=(name,dist.version)
        if key not in cache:
            with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{dist.version}/json',timeout=30) as response:data=json.load(response)
            cache[key]=data
        data=cache[key];hashes=sorted({item['digests']['sha256'] for item in data['urls'] if item['packagetype']=='bdist_wheel' and not item.get('yanked')})
        if not hashes:raise RuntimeError(f'No wheel hashes: {key}')
        marker='; sys_platform == "win32"' if name=='colorama' else ''
        lines.append(f'{name}=={dist.version}{marker} \\')
        lines.extend('    --hash=sha256:'+digest+(' \\' if i<len(hashes)-1 else '') for i,digest in enumerate(hashes))
    (ROOT/'backend'/filename).write_text('\n'.join(lines)+'\n')
    print(filename,len(packages),'packages')
(ROOT/'tmp'/'step16a-pypi-metadata.json').write_text(json.dumps({name+'=='+version:{'license':d['info'].get('license'),'license_expression':d['info'].get('license_expression'),'home_page':d['info'].get('home_page')} for (name,version),d in cache.items()},indent=2))
